axes[0, 1].set_xlabel('Number of Value-Added Services (0 to 6)')
axes[0, 1].set_ylabel('Churn Rate (%)')
axes[0, 1].set_ylim(0, 50)
for b in bars:
    axes[0, 1].text(b.get_x() + b.get_width()/2, b.get_height() + 0.8, f"{b.get_height():.1f}%", ha='center', fontweight='bold')

top10_mi = mi_df.head(10).sort_values(by='MI_Score', ascending=True)
axes[1, 0].barh(top10_mi['Feature'], top10_mi['MI_Score'], color='#388e3c')
axes[1, 0].set_title('C. Top 10 Features by Mutual Information Score', fontsize=12, fontweight='bold')

ab_df = pd.DataFrame(ablation_results).iloc[[0, 1, 3, 4]]
x_pos = np.arange(len(ab_df))
axes[1, 1].bar(x_pos - 0.18, ab_df['Recall'], 0.35, label='Recall', color='#d95f02')
axes[1, 1].bar(x_pos + 0.18, ab_df['F1-Score'], 0.35, label='F1-Score', color='#2b5c8f')
axes[1, 1].set_xticks(x_pos)
axes[1, 1].set_xticklabels(['KNN\n(Unscaled)', 'KNN\n(Scaled+Eng)', 'LogReg\n(No SMOTE)', 'LogReg\n(With SMOTE)'])
axes[1, 1].set_title('D. Empirical Impact of Preprocessing on Test Recall & F1', fontsize=12, fontweight='bold')
axes[1, 1].set_ylim(0, 0.95)
axes[1, 1].legend()

plt.tight_layout()
plt.savefig('PartC_Fig3_Preprocessing_Impact_Verification.png', dpi=300, bbox_inches='tight')
