# ==============================================================================
# PART C: DATA PREPARATION & PREPROCESSING PIPELINE (SELF-CONTAINED)
# ==============================================================================
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import warnings
warnings.filterwarnings('ignore')

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.feature_selection import mutual_info_classif
from imblearn.over_sampling import SMOTE
from sklearn.linear_model import LogisticRegression
from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, roc_auc_score

# 1. Load raw data if not in memory
if 'df_raw' not in locals():
    df_raw = pd.read_csv('WA_Fn-UseC_-Telco-Customer-Churn.csv')
df_clean = df_raw.copy()

# 2. Duplicate & Identifier Treatment
exact_dups = df_clean.duplicated().sum()
id_dups = df_clean['customerID'].duplicated().sum()
df_clean.drop(columns=['customerID'], inplace=True)
feature_dups = df_clean.duplicated().sum()
print(f"Exact Row Duplicates: {exact_dups} | Duplicate CustomerIDs: {id_dups}")
print(f"Identical Feature Profiles (Retained as distinct accounts): {feature_dups}")

# 3. Missing Value Treatment (Domain-Informed Zero Imputation for tenure == 0)
df_clean['TotalCharges'] = pd.to_numeric(df_clean['TotalCharges'], errors='coerce')
null_count = df_clean['TotalCharges'].isnull().sum()
df_clean['TotalCharges'] = df_clean['TotalCharges'].fillna(0.0)
print(f"Imputed {null_count} structural nulls in TotalCharges with 0.0. Remaining Nulls: {df_clean.isnull().sum().sum()}")

# 4. Feature Engineering (3 Domain-Specific Interaction Features)
addon_cols = ['OnlineSecurity', 'OnlineBackup', 'DeviceProtection',
              'TechSupport', 'StreamingTV', 'StreamingMovies']
df_clean['Total_Addons'] = (df_clean[addon_cols] == 'Yes').sum(axis=1)
df_clean['Charge_Difference'] = df_clean['TotalCharges'] - (df_clean['tenure'] * df_clean['MonthlyCharges'])
df_clean['Avg_Monthly_Spend'] = np.where(df_clean['tenure'] > 0,
                                         df_clean['TotalCharges'] / df_clean['tenure'],
                                         df_clean['MonthlyCharges'])

# 5. Categorical Encoding (Binary Mapping + Drop-First One-Hot Encoding)
binary_map = {'Yes': 1, 'No': 0, 'Female': 1, 'Male': 0}
for col in ['gender', 'Partner', 'Dependents', 'PhoneService', 'PaperlessBilling', 'Churn']:
    df_clean[col] = df_clean[col].map(binary_map)

multi_cat_cols = ['MultipleLines', 'InternetService', 'OnlineSecurity', 'OnlineBackup',
                  'DeviceProtection', 'TechSupport', 'StreamingTV', 'StreamingMovies',
                  'Contract', 'PaymentMethod']
df_encoded = pd.get_dummies(df_clean, columns=multi_cat_cols, drop_first=True, dtype=int)
print(f"Dataset shape after Encoding & Feature Engineering: {df_encoded.shape}")

# Export Processed Dataset Deliverable for Submission
df_encoded.to_csv('Telco_Customer_Churn_Processed.csv', index=False)
print("Saved 'Telco_Customer_Churn_Processed.csv' successfully!")

# 6. Stratified Train-Test Split (80% Train / 20% Test BEFORE Scaling & SMOTE)
X = df_encoded.drop(columns=['Churn'])
y = df_encoded['Churn']
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, stratify=y, random_state=42
)
print(f"Train Partition: {X_train.shape} (Churn={y_train.mean()*100:.2f}%) | Test Partition: {X_test.shape} (Churn={y_test.mean()*100:.2f}%)")

# 7. Feature Scaling (StandardScaler fit EXCLUSIVELY on X_train to prevent Data Leakage)
num_scale_cols = ['tenure', 'MonthlyCharges', 'TotalCharges',
                  'Total_Addons', 'Charge_Difference', 'Avg_Monthly_Spend']
scaler = StandardScaler()
X_train_scaled = X_train.copy()
X_test_scaled = X_test.copy()
X_train_scaled[num_scale_cols] = scaler.fit_transform(X_train[num_scale_cols])
X_test_scaled[num_scale_cols] = scaler.transform(X_test[num_scale_cols])

# 8. Feature Selection Audit via Mutual Information (Filter Method on Train)
mi_scores = mutual_info_classif(X_train_scaled, y_train, random_state=42)
mi_df = pd.DataFrame({'Feature': X_train_scaled.columns, 'MI_Score': mi_scores}).sort_values(by='MI_Score', ascending=False)

# 9. Class Balancing via SMOTE (Applied ONLY to Training Set)
smote = SMOTE(random_state=42)
X_train_smote, y_train_smote = smote.fit_resample(X_train_scaled, y_train)
print(f"Training Set Before SMOTE: Class 0={(y_train==0).sum()}, Class 1={(y_train==1).sum()}")
print(f"Training Set After SMOTE:  Class 0={(y_train_smote==0).sum()}, Class 1={(y_train_smote==1).sum()}")

# 10. Ablation Study: Quantifying Impact of Preprocessing on Model Performance
X_tr_raw = X_train.drop(columns=['Total_Addons', 'Charge_Difference', 'Avg_Monthly_Spend'])
X_te_raw = X_test.drop(columns=['Total_Addons', 'Charge_Difference', 'Avg_Monthly_Spend'])

ablation_models = [
    ("KNN (Raw Unscaled, No Eng.)", KNeighborsClassifier(n_neighbors=11).fit(X_tr_raw, y_train), X_te_raw),
    ("KNN (Scaled + Engineered)", KNeighborsClassifier(n_neighbors=11).fit(X_train_scaled, y_train), X_test_scaled),
    ("LogReg (Unscaled, Imbalanced)", LogisticRegression(max_iter=2000, random_state=42).fit(X_tr_raw, y_train), X_te_raw),
    ("LogReg (Scaled + Eng., Imbalanced)", LogisticRegression(max_iter=2000, random_state=42).fit(X_train_scaled, y_train), X_test_scaled),
    ("LogReg (Scaled + Eng. + SMOTE)", LogisticRegression(max_iter=2000, random_state=42).fit(X_train_smote, y_train_smote), X_test_scaled)
]

ablation_results = []
for stage_name, clf, X_eval in ablation_models:
    p_label = clf.predict(X_eval)
    p_prob = clf.predict_proba(X_eval)[:, 1]
    ablation_results.append({
        'Preprocessing Stage': stage_name,
        'Accuracy': round(accuracy_score(y_test, p_label), 4),
        'Precision': round(precision_score(y_test, p_label), 4),
        'Recall': round(recall_score(y_test, p_label), 4),
        'F1-Score': round(f1_score(y_test, p_label), 4),
        'ROC-AUC': round(roc_auc_score(y_test, p_prob), 4)
    })
print("\n--- ABLATION TABLE: IMPACT OF PREPROCESSING ON MODEL PERFORMANCE ---")
display(pd.DataFrame(ablation_results))

# 11. Plot Figure 3: Visual Verification of Preprocessing Pipeline
fig, axes = plt.subplots(2, 2, figsize=(16, 11))
scaled_melt = X_train_scaled[['tenure', 'MonthlyCharges', 'TotalCharges']].melt(var_name='Feature', value_name='Z_Score')
sns.boxplot(data=scaled_melt, x='Feature', y='Z_Score', hue='Feature', palette='Blues', legend=False, ax=axes[0, 0])
